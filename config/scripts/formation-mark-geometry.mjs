// Formation mark geometry, shared by the SVG masters and the PNG renders so both stay identical.
// Grid and colours come from docs/STYLEGUIDE.md "Brand".

export const FORMATION_COLORS = {
  ink: '#17181C',
  paper: '#ECE9E3',
  stone: '#CBC9C4',
  coral: '#EF7A5A',
  darkStone: '#3A3B40',
  amber: '#FBBF24',
  coralDeep: '#E25630'
}

// D ink (the M), s stone, C coral.
export const FORMATION_DOT_MAP = ['DsssD', 'DDsDD', 'DsCsD', 'DsssD', 'DsssD']

export const FORMATION_THEMES = {
  paper: {
    tile: FORMATION_COLORS.paper,
    m: FORMATION_COLORS.ink,
    stone: FORMATION_COLORS.stone,
    centre: FORMATION_COLORS.coral,
    // Paper on white is 1.21:1, so the tile edge needs Ink at 10%.
    hairline: mixHex(FORMATION_COLORS.paper, FORMATION_COLORS.ink, 0.1)
  },
  dark: {
    tile: FORMATION_COLORS.ink,
    m: FORMATION_COLORS.paper,
    stone: FORMATION_COLORS.darkStone,
    centre: FORMATION_COLORS.coral,
    hairline: null
  },
  dev: {
    tile: FORMATION_COLORS.ink,
    m: FORMATION_COLORS.paper,
    stone: FORMATION_COLORS.darkStone,
    centre: FORMATION_COLORS.amber,
    hairline: null
  }
}

// Hand-fit small marks (12 ink + 1 coral). Pixel values; other sizes scale the 16px fit.
const SMALL_FITS = {
  16: { dot: 2, gap: 1, margin: 1, radius: 4 },
  // 20 and 24 trade the 2:1 dot-to-gap ratio or centring for whole-pixel dot edges.
  20: { dot: 2, gap: 2, margin: 1, radius: 4.5 },
  24: { dot: 3, gap: 1, margin: 2, radius: 6 },
  32: { dot: 4, gap: 2, margin: 2, radius: 8 }
}

export function smallFit(size) {
  if (SMALL_FITS[size]) {
    return SMALL_FITS[size]
  }
  const u = size / 16
  return { dot: 2 * u, gap: u, margin: u, radius: 4 * u }
}

function fullFit(size) {
  const u = size / 20
  return { dot: 2 * u, gap: u, margin: 3 * u, radius: 4.5 * u }
}

export function mixHex(base, over, amount) {
  const a = hexToRgb(base)
  const b = hexToRgb(over)
  const mix = (x, y) => Math.round(x + (y - x) * amount)
  return rgbToHex({ r: mix(a.r, b.r), g: mix(a.g, b.g), b: mix(a.b, b.b) })
}

export function hexToRgb(hex) {
  const n = Number.parseInt(hex.slice(1), 16)
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 }
}

function rgbToHex({ r, g, b }) {
  const hex = [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('')
  return `#${hex.toUpperCase()}`
}

/**
 * Shapes for one tile. `small` drops the stone dots (used under 48px).
 * `offset`/`tileSize` place the tile inside a larger canvas (macOS 824-in-1024).
 */
export function formationTileShapes({ tileSize, offset = 0, small = false, theme = 'paper' }) {
  const colors = FORMATION_THEMES[theme]
  const fit = small ? smallFit(tileSize) : fullFit(tileSize)
  const shapes = []
  const tile = { type: 'rect', x: offset, y: offset, w: tileSize, h: tileSize, r: fit.radius }
  if (colors.hairline) {
    const line = Math.max(1, Math.round(tileSize / 256))
    shapes.push({ ...tile, color: colors.hairline })
    shapes.push({
      type: 'rect',
      x: offset + line,
      y: offset + line,
      w: tileSize - 2 * line,
      h: tileSize - 2 * line,
      r: fit.radius - line,
      color: colors.tile
    })
  } else {
    shapes.push({ ...tile, color: colors.tile })
  }
  const pitch = fit.dot + fit.gap
  // Coral is 2.28:1 on Paper; at small sizes the M's vertex needs Coral deep (3.09:1) to hold in greyscale.
  const centre = small && theme === 'paper' ? FORMATION_COLORS.coralDeep : colors.centre
  FORMATION_DOT_MAP.forEach((row, rowIndex) => {
    ;[...row].forEach((cell, colIndex) => {
      if (small && cell === 's') {
        return
      }
      const color = cell === 'D' ? colors.m : cell === 'C' ? centre : colors.stone
      shapes.push({
        type: 'circle',
        cx: offset + fit.margin + fit.dot / 2 + colIndex * pitch,
        cy: offset + fit.margin + fit.dot / 2 + rowIndex * pitch,
        r: fit.dot / 2,
        color
      })
    })
  })
  return shapes
}

// macOS: the tile is 824 of a 1024 canvas (Big Sur grid), scaled for smaller canvases.
export function macCanvasShapes(canvasSize, theme = 'paper') {
  const scale = canvasSize / 1024
  return formationTileShapes({ tileSize: 824 * scale, offset: 100 * scale, theme })
}

const fmt = (n) => String(Math.round(n * 1000) / 1000)

export function shapesToSvg(size, shapes, title = 'Muster') {
  const body = shapes
    .map((s) =>
      s.type === 'rect'
        ? `  <rect x="${fmt(s.x)}" y="${fmt(s.y)}" width="${fmt(s.w)}" height="${fmt(s.h)}" rx="${fmt(s.r)}" fill="${s.color}"/>`
        : `  <circle cx="${fmt(s.cx)}" cy="${fmt(s.cy)}" r="${fmt(s.r)}" fill="${s.color}"/>`
    )
    .join('\n')
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" role="img" aria-label="${title}">
  <title>${title}</title>
  <!-- Generated by config/scripts/render-formation-icons.mjs. Edit the geometry there, not here. -->
${body}
</svg>
`
}
